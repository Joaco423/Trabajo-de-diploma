-- Script de creacion de la base de datos de CAFECCINO 2.0
-- Generado a partir de la base CAFECCINO1 (estructura completa + datos de configuracion).
-- Datos incluidos: idiomas, controles y traducciones, permisos y perfiles, y el usuario administrador.
-- No incluye movimientos (clientes, productos, mesas, mozos, pedidos, reservas, eventos).
-- El programa crea la base (CAFECCINO2) y ejecuta estos lotes dentro de ella; despues recalcula los digitos verificadores.

-- ===================== TABLAS =====================
CREATE TABLE [dbo].[Atencion] (
    [CodigoPedido] int NOT NULL,
